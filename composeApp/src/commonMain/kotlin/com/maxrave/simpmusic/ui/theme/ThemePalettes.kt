/**
 * Theme color source value for the curated named-palette picker.
 *
 * The [DataStoreManager] interface lives in the `core` submodule and only
 * declares [DataStoreManager.THEME_COLOR_DEFAULT] /
 * [DataStoreManager.THEME_COLOR_WALLPAPER] /
 * [DataStoreManager.THEME_COLOR_CUSTOM]. Because
 * [DataStoreManager.setThemeColorSource] takes an arbitrary [String], we
 * add this value on the app side without a submodule change. The selected
 * palette's seed color is persisted through [DataStoreManager.customThemeColor]
 * and resolved in [AppTheme] (which treats a `PALETTE` source identically to
 * `CUSTOM` for seed-color derivation).
 */
const val THEME_COLOR_PALETTE = "PALETTE"

/**
 * A curated named theme palette. [seedHex] is an 8-digit ARGB hex string
 * persisted in [DataStoreManager.customThemeColor]; [AppTheme] feeds it to
 * MaterialKolor to generate the full light/dark ColorScheme.
 */
data class ThemePalette(
    val id: String,
    val nameRes: StringResource,
    val seedHex: String,
) {
    /** MaterialKolor seed for this palette. Falls back to the app default if malformed. */
    val seedColor: Color
        get() = parseThemeColorHex(seedHex) ?: seed
}

/**
 * Curated named theme palettes shown in Settings → Theme color → Palette.
 *
 * Seeds are tuned to read well in both the AMOLED-dark and the neutral-light
 * schemes generated by [AppTheme]. Each entry's [ThemePalette.seedHex] is
 * written to [DataStoreManager.customThemeColor] when the user picks it, so
 * the selection survives restarts and is shared across platforms.
 */
val ThemePalettes: List<ThemePalette> =
    listOf(
        ThemePalette("ocean", Res.string.theme_palette_ocean, "FF0288D1"),
        ThemePalette("sunset", Res.string.theme_palette_sunset, "FFE65100"),
