    )

/**
 * The palette whose seed matches [seedHex], or null when the stored color
 * is not one of the curated seeds (e.g. a free-form custom color).
 */
fun findThemePalette(seedHex: String?): ThemePalette? =
    seedHex?.let { hex -> ThemePalettes.firstOrNull { it.seedHex.equals(hex, ignoreCase = true) } }
